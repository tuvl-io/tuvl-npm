import { describe, expect, it } from "vitest";
import doc from "./__fixtures__/openapi.json";
import { generate, tsType, type OpenApiDocument } from "./generate";

describe("tsType", () => {
  it("maps the JSON Schema tuvl emits", () => {
    expect(tsType({ type: "string", enum: ["low", "high"] })).toBe('"low" | "high"');
    expect(tsType({ anyOf: [{ type: "string", format: "uuid" } as never, { type: "null" }] })).toBe("string | null");
    expect(tsType({ type: ["string", "null"] })).toBe("string | null");
    expect(tsType({ type: "array", items: { type: "integer" } })).toBe("Array<number>");
    expect(tsType({ type: "object" })).toBe("Record<string, unknown>");
    expect(tsType({})).toBe("unknown");
    expect(tsType({ type: "object", properties: { "a-b": { type: "boolean" }, c: { type: "number" } }, required: ["c"] })).toBe(
      '{\n  "a-b"?: boolean;\n  c: number;\n}',
    );
  });
});

describe("generate", () => {
  it("types each exported trigger from the sample project's OpenAPI", () => {
    const code = generate(doc as OpenApiDocument, "sample");
    expect(code).toContain("// Generated by `tuvl-client generate` from sample.");
    expect(code).toContain("  triage_ticket: {");
    for (const field of ["subject: string;", "body: string;", "customer_email: string;"]) expect(code).toContain(field);
    expect(code).toMatch(/output: \{\n\s+category:/); // the default end (201), not the 200 'dismissed' end
    expect(code).toContain('category: "billing" | "technical" | "account";');
    expect(code).toMatch(/ends: \{\n\s+200: \{/);
    expect(code).not.toContain("202:");
    expect(code.match(/^ {2}\S.*: \{$/gm)).toHaveLength(1); // only operations with x-tuvl-workflow
  });
});
