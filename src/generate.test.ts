import { describe, expect, it } from "vitest";
import doc from "./__fixtures__/openapi.json";
import { countWorkflows, generate, tsType, type OpenApiDocument } from "./generate";

describe("tsType", () => {
  it("maps the JSON Schema tuvl emits", () => {
    expect(tsType({ type: "string", enum: ["low", "high"] })).toBe('"low" | "high"');
    expect(tsType({ anyOf: [{ type: "string", format: "uuid" } as never, { type: "null" }] })).toBe("string | null");
    expect(tsType({ type: ["string", "null"] })).toBe("string | null");
    expect(tsType({ type: "array", items: { type: "integer" } })).toBe("Array<number>");
    expect(tsType({ type: "object" })).toBe("Record<string, unknown>");
    expect(tsType({})).toBe("unknown");
    expect(tsType({ type: "something-new" } as never)).toBe("unknown");
    expect(tsType({ type: "object", properties: { "a-b": { type: "boolean" }, c: { type: "number" } }, required: ["c"] })).toBe(
      '{\n  "a-b"?: boolean;\n  c: number;\n}',
    );
  });
});

describe("generate", () => {
  it("types each exported trigger from the sample project's OpenAPI", () => {
    const code = generate(doc as OpenApiDocument, "sample");
    expect(code).toContain("// Generated by `tuvl-client generate` from sample.");
    expect(code).toContain("  triage_ticket: {");
    for (const field of ["subject: string;", "body: string;", "customer_email: string;"]) expect(code).toContain(field);
    expect(code).toMatch(/output: \{\n\s+category:/); // the default end (201), not the 200 'dismissed' end
    expect(code).toContain('category: "billing" | "technical" | "account";');
    expect(code).toMatch(/ends: \{\n\s+200: \{/);
    expect(code).not.toContain("202:");
    expect(code.match(/^ {2}\S.*: \{$/gm)).toHaveLength(1); // only operations with x-tuvl-workflow
  });
});

describe("file inputs", () => {
  it("types a multipart file part as Blob", () => {
    expect(tsType({ type: "string", format: "binary" })).toBe("Blob");
    const out = generate({
      paths: {
        "/t/intake": {
          post: {
            "x-tuvl-workflow": "intake",
            requestBody: {
              content: {
                "multipart/form-data": {
                  schema: {
                    type: "object",
                    properties: {
                      doc: { type: "string", format: "binary" },
                      pages: { type: "array", items: { type: "string", format: "binary" } },
                      note: { type: "string" },
                    },
                    required: ["doc"],
                  },
                },
              },
            },
            responses: { "200": { description: "END" } },
          },
        },
      },
    });
    expect(out).toContain("doc: Blob;");
    expect(out).toContain("pages?: Array<Blob>;");
    expect(out).toContain("note?: string;");
  });
});

describe("the schema corners", () => {
  it("joins oneOf like anyOf and de-duplicates", () => {
    expect(tsType({ oneOf: [{ type: "string" }, { type: "number" }, { type: "string" }] })).toBe("string | number");
  });

  it("does not follow a $ref it cannot resolve", () => {
    expect(tsType({ $ref: "#/components/schemas/Thing" } as never)).toBe("unknown");
  });

  it("types an open object as a record", () => {
    expect(tsType({ type: "object", additionalProperties: true })).toBe("Record<string, unknown>");
  });

  it("merges path and query parameters into the input", () => {
    const out = generate({
      paths: {
        "/t/{id}": {
          post: {
            "x-tuvl-workflow": "lookup",
            parameters: [
              { name: "id", in: "path", required: true, schema: { type: "string" } },
              { name: "verbose", in: "query", schema: { type: "boolean" } },
              { name: "x-trace", in: "header", schema: { type: "string" } },
            ],
            responses: { "200": { description: "END" } },
          },
        },
      },
    });
    expect(out).toContain("id: string;");
    expect(out).toContain("verbose?: boolean;");
    expect(out).not.toContain("x-trace");
  });

  it("an empty document types no workflows", () => {
    expect(countWorkflows({})).toBe(0);
    expect(countWorkflows({ paths: {} })).toBe(0);
    expect(generate({ paths: {} })).toContain("export type Workflows = {\n};");
  });

  it("counts only operations that carry x-tuvl-workflow", () => {
    expect(countWorkflows(doc as OpenApiDocument)).toBe(1);
  });
});


describe("generate: choosing the default end", () => {
  const op = (responses: Record<string, unknown>) =>
    ({
      openapi: "3.1.0",
      paths: {
        "/api/workflows/w/runs": {
          post: { "x-tuvl-workflow": "w", responses },
        },
      },
    }) as unknown as OpenApiDocument;
  const body = (key: string) => ({ content: { "application/json": { schema: { type: "object", properties: { [key]: { type: "string" } }, required: [key] } } } });

  it("takes the end described as END, else the lowest 2xx", () => {
    const described = generate(op({ "200": { description: "other", ...body("a") }, "201": { description: "END", ...body("b") } }));
    expect(described).toMatch(/output: \{\n\s+b: string;/);
    const lowest = generate(op({ "201": { description: "x", ...body("b") }, "200": { description: "y", ...body("a") } }));
    expect(lowest).toMatch(/output: \{\n\s+a: string;/);
  });

  it("has no output when no end succeeds", () => {
    expect(generate(op({ "404": { description: "gone", ...body("a") } }))).toContain("output: undefined;");
  });
});
