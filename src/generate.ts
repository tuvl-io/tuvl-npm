/**
 * `tuvl-client generate`: typed workflow contracts from a tuvl server's
 * `/openapi.json` (spec §15.5). Each trigger operation carries
 * `x-tuvl-workflow`; its parameters and JSON body form the input, and each
 * end status its body.
 */

type Schema = {
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  enum?: unknown[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  additionalProperties?: boolean | Schema;
  description?: string;
  format?: string;
};

interface Operation {
  "x-tuvl-workflow"?: string;
  parameters?: { name: string; in: string; required?: boolean; schema?: Schema }[];
  requestBody?: { content?: Record<string, { schema?: Schema }> };
  responses?: Record<string, { description?: string; content?: Record<string, { schema?: Schema }> }>;
}

export interface OpenApiDocument {
  paths?: Record<string, Record<string, Operation>>;
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string) => (IDENT.test(name) ? name : JSON.stringify(name));

/** The TypeScript type for a JSON Schema (the subset tuvl emits). */
export function tsType(schema: Schema | undefined, indent = ""): string {
  if (!schema || Object.keys(schema).length === 0) return "unknown";
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ") || "never";
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return [...new Set(union.map((s) => tsType(s, indent)))].join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((t) => tsType({ ...schema, type: t }, indent)).join(" | ");
  switch (schema.type) {
    case "string":
      return schema.format === "binary" ? "Blob" : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `Array<${tsType(schema.items, indent)}>`;
    case "object":
    case undefined: {
      const props = Object.entries(schema.properties ?? {});
      if (props.length === 0) return schema.type === "object" ? "Record<string, unknown>" : "unknown";
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = props.map(([name, prop]) => {
        const doc = prop.description ? `${inner}/** ${prop.description.replace(/\*\//g, "* /")} */\n` : "";
        return `${doc}${inner}${key(name)}${required.has(name) ? "" : "?"}: ${tsType(prop, inner)};`;
      });
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      return "unknown";
  }
}

function inputSchema(op: Operation): Schema {
  const properties: Record<string, Schema> = {};
  const required: string[] = [];
  for (const p of op.parameters ?? []) {
    if (p.in !== "path" && p.in !== "query") continue;
    properties[p.name] = p.schema ?? {};
    if (p.required) required.push(p.name);
  }
  const content = op.requestBody?.content;
  const body = (content?.["multipart/form-data"] ?? content?.["application/json"])?.schema;
  Object.assign(properties, body?.properties ?? {});
  required.push(...(body?.required ?? []));
  return { type: "object", properties, required };
}

/** How many workflows `generate` will type: the operations that carry `x-tuvl-workflow`. */
export function countWorkflows(doc: OpenApiDocument): number {
  let count = 0;
  for (const methods of Object.values(doc.paths ?? {})) {
    for (const op of Object.values(methods)) if (op["x-tuvl-workflow"]) count++;
  }
  return count;
}

/** Generate the `Workflows` type module from an OpenAPI document. */
export function generate(doc: OpenApiDocument, source = "openapi.json"): string {
  const workflows: string[] = [];
  for (const methods of Object.values(doc.paths ?? {})) {
    for (const op of Object.values(methods)) {
      const name = op["x-tuvl-workflow"];
      if (!name) continue;
      const ends = Object.entries(op.responses ?? {})
        .filter(([status]) => /^\d{3}$/.test(status) && status !== "202" && status !== "422")
        .map(([status, r]) => [Number(status), r.content?.["application/json"]?.schema, r.description ?? ""] as const)
        .sort(([a], [b]) => a - b);
      // the default end is described as "END"; else the lowest 2xx
      const ok =
        ends.find(([, , description]) => description.split(", ").includes("END")) ??
        ends.find(([status]) => status < 300);
      const indent = "      ";
      const endLines = ends.map(([status, schema]) => `${indent}${status}: ${schema ? tsType(schema, indent) : "undefined"};`);
      workflows.push(
        [
          `  ${key(name)}: {`,
          `    input: ${tsType(inputSchema(op), "    ")};`,
          `    output: ${ok?.[1] ? tsType(ok[1], "    ") : "undefined"};`,
          `    ends: {\n${endLines.join("\n")}\n    };`,
          `  };`,
        ].join("\n"),
      );
    }
  }
  return [
    `// Generated by \`tuvl-client generate\` from ${source}. Do not edit.`,
    "",
    "/** Workflow name → `{ input, output, ends }`, for `new TuvlClient<Workflows>(...)`. */",
    "export type Workflows = {",
    ...workflows,
    "};",
    "",
  ].join("\n");
}
